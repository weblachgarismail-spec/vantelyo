const LANG_STORAGE_KEY = 'sli-lang';
let currentLang = 'en';

function t(key, lang) {
  const l = lang || currentLang;
  return (translations[l] && translations[l][key]) || translations.en[key] || key;
}

function detectLang() {
  let urlLang = null;
  try {
    urlLang = new URLSearchParams(window.location.search).get('lang');
  } catch (e) {}
  let saved = null;
  try {
    saved = window.localStorage.getItem(LANG_STORAGE_KEY);
  } catch (e) {}
  if (urlLang && translations[urlLang]) return urlLang;
  if (saved && translations[saved]) return saved;
  // Article pages declare their content language; use it for the UI too so an
  // Arabic or French article opens with matching navigation labels.
  const contentLang = document.documentElement.getAttribute('data-content-lang');
  if (contentLang && translations[contentLang]) return contentLang;
  return 'en';
}

function setLang(lang, options) {
  if (!translations[lang]) return;
  const opts = options || {};
  currentLang = lang;

  // Article pages declare the language of their content; keep it accurate
  // even when the visitor switches the site UI language.
  const contentLang = document.documentElement.getAttribute('data-content-lang');
  const effectiveLang = contentLang || lang;
  document.documentElement.lang = effectiveLang;
  document.documentElement.dir = effectiveLang === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    const val = translations[lang][key];
    if (!val) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    const val = translations[lang][el.getAttribute('data-i18n-aria')];
    if (val) el.setAttribute('aria-label', val);
  });

  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    document.title = translations[lang][titleEl.getAttribute('data-i18n')] || document.title;
  }

  if (opts.save !== false) {
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch (e) {}
    try {
      const url = new URL(window.location.href);
      if (lang === 'en') url.searchParams.delete('lang');
      else url.searchParams.set('lang', lang);
      window.history.replaceState(null, '', url.toString());
    } catch (e) {}
  }

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang } }));
}

function getLang() {
  return currentLang;
}

function initI18n() {
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
      setLang(btn.dataset.lang);
    });
  });
  setLang(detectLang(), { save: false });
}
